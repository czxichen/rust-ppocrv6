"""Emit the ground truth that is actually visible in each fixture, for rec_accuracy.rs.

`gen_bench_images.py` draws every line at a fixed x on a fixed-width canvas, so the longer
lines run off the right edge: `bench_long_line.png` is 1440px wide and holds 37 of its 117
characters, and doc body lines 1, 2 and 6 have ink touching the canvas edge. Scoring the
engine against the generator's source string charges it for characters that were never
rasterised -- on the first run of the accuracy harness this read as "the rec model is 32%
accurate" when it had in fact reproduced the visible text exactly.

This renders each line the same way the generator does and binary-searches the longest
prefix whose ink fits inside the canvas. The result is written as a Rust source file so
the harness and this script cannot drift apart.

Usage:
    python tools/profiling/gen_visible_truth.py
    cargo run --release --example rec_accuracy
"""

import os
import re
from functools import lru_cache

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
GEN = os.path.join(HERE, "gen_bench_images.py")
OUT = os.path.join(REPO, "examples", "rec_accuracy", "truth.rs")

src = open(GEN, "rb").read().decode("utf-8")
POOL = [m.group(1) for m in re.finditer(r'(?:CN|EN|MIX) = "(.*?)"', src)] + [
    "文本检测与识别端到端耗时统计，包含预处理、前向推理与后处理阶段。",
    "AVX2 与 FMA 微内核在 Windows 平台可达到硬件理论峰值的 80% 以上。",
]
TITLE = re.search(r'd\.text\(\(60, 30\), "(.*?)"', src).group(1)
SINGLE = re.search(r'd\.text\(\(24, 36\), "(.*?)"', src).group(1)

# case name -> (drawn text, x, y, font px, canvas width)
CASES = [
    ("single line 36pt", SINGLE, 24, 36, 36, 480),
    ("long mixed CN/EN 38pt", POOL[0] + POOL[1], 12, 12, 38, 1440),
    ("doc title 30pt", TITLE, 60, 30, 30, 1000),
    ("doc body 1 CN 24pt", "[01] " + POOL[0], 60, 90, 24, 1000),
    ("doc body 2 EN 24pt", "[02] " + POOL[1], 60, 135, 24, 1000),
    ("doc body 3 MIX 24pt", "[03] " + POOL[2], 60, 180, 24, 1000),
    ("doc body 4 CN punct 24pt", "[04] " + POOL[3], 60, 225, 24, 1000),
    ("doc body 5 AVX2 24pt", "[05] " + POOL[4], 60, 270, 24, 1000),
]


@lru_cache(maxsize=None)
def font(px: int) -> ImageFont.FreeTypeFont:
    return ImageFont.truetype("C:/Windows/Fonts/msyh.ttc", px)


def fits(text: str, x: int, y: int, px: int, width: int) -> bool:
    im = Image.new("L", (width, 400), 255)
    ImageDraw.Draw(im).text((x, y), text, font=font(px), fill=0)
    bb = im.point(lambda v: 255 if v < 128 else 0).getbbox()
    return bb is not None and bb[2] < width - 1


def visible_prefix(text: str, x: int, y: int, px: int, width: int) -> str:
    """Longest prefix of `text` whose ink fits within `width`.

    Monotone: once a glyph runs past the right edge, so does every longer prefix.
    """
    if fits(text, x, y, px, width):
        return text
    lo, hi = 0, len(text)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if fits(text[:mid], x, y, px, width):
            lo = mid
        else:
            hi = mid - 1
    return text[:lo]


def add_spacing_fixes(lines: list[tuple[str, str]]) -> list[tuple[str, str]]:
    """Re-insert spaces the renderer does not actually draw.

    The font gives 'C' a large right side bearing, so `zero C++ runtime` rasterises with a
    9px gap between the C and the first '+' against 4px between the two '+'s -- the image
    genuinely reads "C + +", and rec transcribes it faithfully. Scoring against the source
    string calls that a 3-character error when the model is right. Measured in
    `tools/profiling/` while chasing exactly this case.
    """
    # Substring, not whole string: this case is clipped to "...dependenc", so an equality
    # key would never fire.
    fixes = [("zero C++ runtime", "zero C + + runtime")]
    out = []
    for name, truth, note in lines:
        for src_sub, fixed_sub in fixes:
            if src_sub in truth:
                truth = truth.replace(src_sub, fixed_sub)
        out.append((name, truth, note))
    return out


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    lines = [
        "// @generated by tools/profiling/gen_visible_truth.py -- do not edit by hand.",
        "//",
        "// Ground truth for the `bench_*.png` fixtures, trimmed to the characters that are",
        "// actually rasterised in the image. The generators draw each line at a fixed x on a",
        "// fixed-width canvas, so longer lines run off the right edge and the tail of the",
        "// string is not in the PNG at all.",
        "",
        "/// `(case name, ground truth)` for the fixtures drawn by `gen_bench_images.py`.",
        "pub const BENCH_TRUTH: &[(&str, &str)] = &[",
    ]
    clipped = 0
    rows = []
    for name, drawn, x, y, px, width in CASES:
        truth = visible_prefix(drawn, x, y, px, width)
        note = ""
        if len(truth) < len(drawn):
            note = f"  // clipped: {len(truth)}/{len(drawn)} chars fit on the canvas"
            clipped += 1
        rows.append((name, truth, note))
    for name, truth, note in add_spacing_fixes(rows):
        lines.append(f"    ({rust_str(name)}, {rust_str(truth)}),{note}")
    lines += [
        "];",
        "",
    ]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}  ({len(CASES)} cases, {clipped} clipped by their canvas)")


if __name__ == "__main__":
    main()
